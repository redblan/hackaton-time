/**
 * Ответы для DEMO_MODE. Перед питчем впишите сюда ответы на вопросы из сценария демо:
 * ключевые слова -> ответ. Тогда показ не зависит от интернета и лимитов API.
 */
const SCRIPTED: { keywords: string[]; answer: string }[] = [
  {
    keywords: ["привет", "здравствуй", "что умеешь", "кто ты"],
    answer:
      "Здравствуйте! Я ИИ-ассистент платформы. Могу рассказать о текущей ситуации по заявкам, подсказать, на что обратить внимание, и помочь сформулировать новое обращение.",
  },
  {
    keywords: ["приоритет", "внимание", "срочн", "важн"],
    answer:
      "В первую очередь стоит разобрать заявки с высоким приоритетом в статусе «Новая»: они дольше всего ждут реакции. Затем — заявки «В работе» старше двух недель, там высок риск, что работа зависла.",
  },
];

export function demoAnswer(question: string, context: string): string {
  const q = question.toLowerCase();
  const hit = SCRIPTED.find((s) => s.keywords.some((k) => q.includes(k)));
  if (hit) return hit.answer;
  if (/(сколько|статистик|сводк|ситуац|цифр)/.test(q)) {
    return `Вот актуальная сводка по платформе:\n\n${context}`;
  }
  return `(Демо-режим) Ассистент работает без подключения к модели. Подключите LLM в .env или добавьте ответ на этот вопрос в demo-answers.ts.\n\nТекущие данные:\n${context}`;
}
