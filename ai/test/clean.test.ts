import { describe, expect, it } from "vitest";
import { cleanReply } from "../src/prompt";

describe("чистка ответа модели (прогон M4 на qwen2.5:3b)", () => {
  it("убирает метки «Правило:», «Пример:»", () => {
    expect(cleanReply("Правило: никаких искр. Свет не трогать, кран перекрыть.")).toBe("Никаких искр. Свет не трогать, кран перекрыть.");
    expect(cleanReply("Я уже говорил: Пример: даже щелчок выключателя даёт искру.")).toBe("Я уже говорил: даже щелчок выключателя даёт искру.");
  });
  it("пустышку отбрасывает — тогда ответит шаблон", () => {
    expect(cleanReply("я уже говорил: Пример.")).toBe("");
    expect(cleanReply("Хорошо.")).toBe("");
  });
  it("нормальный ответ не трогает", () => {
    expect(cleanReply("Под стол, быстро! От окна подальше.")).toBe("Под стол, быстро! От окна подальше.");
  });
});
